#!/usr/bin/env python3
"""One grammar source, three artifacts (3.0, A6).

    spec/soma.grammar  ->  spec/soma.gbnf                         constrained decoding
                           spec/grammar.md                        the grammar, to read
                           editors/tree-sitter-soma/grammar.js    editors

`--check` writes nothing and fails when an artifact is out of date.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "spec", "soma.grammar")

# ── read the source ────────────────────────────────────────────────────

def read_source():
    """[(kind, payload)]: ('title', text) | ('prose', text) | ('rule', (name, body, lexical))"""
    items, lexical = [], False
    for line in open(SOURCE, encoding="utf-8").read().split("\n"):
        if line.startswith("## "):
            items.append(("title", line[3:].strip()))
        elif line.strip() == "# @lexical":
            lexical = True
        elif line.startswith("#"):
            items.append(("prose", line[1:].strip()))
        elif "::=" in line:
            name, body = line.split("::=", 1)
            items.append(("rule", (name.strip(), body.strip(), lexical)))
            lexical = False
        elif line.strip():
            raise SystemExit(f"spec/soma.grammar: a line that is no rule, comment or title: {line!r}")
    return items

# ── GBNF expression parser (for the tree-sitter translation) ──────────

def tokenize(body):
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c.isspace():
            i += 1
        elif c == '"':
            j = i + 1
            while body[j] != '"':
                j += 2 if body[j] == "\\" else 1
            out.append(("lit", json.loads(body[i:j + 1])))
            i = j + 1
        elif c == "[":
            j = i + 1
            if body[j] == "^": j += 1
            if body[j] == "]": j += 1
            while body[j] != "]":
                j += 2 if body[j] == "\\" else 1
            out.append(("class", body[i:j + 1]))
            i = j + 1
        elif c in "()|*+?":
            out.append((c, c)); i += 1
        else:
            j = i
            while j < len(body) and (body[j].isalnum() or body[j] == "-"): j += 1
            if j == i: raise SystemExit(f"spec/soma.grammar: unexpected {c!r} in {body!r}")
            out.append(("ref", body[i:j])); i = j
    return out

def parse(body):
    toks = tokenize(body)
    pos = 0
    def alt():
        nonlocal pos
        branches = [seq()]
        while pos < len(toks) and toks[pos][0] == "|":
            pos += 1
            branches.append(seq())
        return branches[0] if len(branches) == 1 else ("alt", branches)
    def seq():
        nonlocal pos
        parts = []
        while pos < len(toks) and toks[pos][0] not in ("|", ")"):
            parts.append(post())
        return parts[0] if len(parts) == 1 else ("seq", parts)
    def post():
        nonlocal pos
        kind, value = toks[pos]; pos += 1
        if kind == "(":
            node = alt()
            pos += 1  # )
        else:
            node = (kind, value)
        while pos < len(toks) and toks[pos][0] in "*+?":
            node = (toks[pos][0], node); pos += 1
        return node
    return alt()

# ── GBNF ───────────────────────────────────────────────────────────────

def gbnf(items):
    out = ["# Soma grammar (GBNF) — generated by tools/gen_grammar.py from spec/soma.grammar; do not edit.",
           "# Every program `soma` parses is in this grammar; it is loose in the `rules`, `runtime`,",
           "# `scale`, `cost` and `protocol` blocks and knows none of `soma check`'s rules.", ""]
    for kind, payload in items:
        if kind == "title":
            out += ["", f"# ── {payload} " + "─" * max(4, 60 - len(payload))]
        elif kind == "rule":
            name, body, lexical = payload
            if lexical: out.append("# @lexical")
            out.append(f"{name} ::= {body}")
    return "\n".join(out) + "\n"

# ── Markdown ───────────────────────────────────────────────────────────

def markdown(items):
    out = ["<!-- generated by tools/gen_grammar.py from spec/soma.grammar; do not edit -->", ""]
    block, first = [], True
    def flush():
        nonlocal block
        if block:
            out.extend(["```gbnf"] + block + ["```", ""])
            block = []
    prose = []
    def flush_prose():
        nonlocal prose
        if prose:
            out.extend([" ".join(p for p in prose if p) if all(prose) else "\n".join(prose), ""])
            prose = []
    for kind, payload in items:
        if kind == "title":
            flush(); flush_prose()
            out.extend([("# " if first else "## ") + payload, ""])
            first = False
        elif kind == "prose":
            flush()
            if payload == "": flush_prose()
            else: prose.append(payload)
        else:
            flush_prose()
            name, body, lexical = payload
            block.append(f"{name} ::= {body}" + ("    # token" if lexical else ""))
    flush(); flush_prose()
    return "\n".join(out).rstrip() + "\n"

# ── tree-sitter ────────────────────────────────────────────────────────

SKIP = {"ws", "ws1", "hws"}          # tree-sitter's `extras` are the whitespace

def js_name(name): return name.replace("-", "_")

def class_regex(cls):
    return "[^\\s\\S]" if cls == "[^]" else cls   # (never produced: `[^]` is "any" below)

def regex_of(node, rules):
    """A lexical rule as one regular expression."""
    kind = node[0]
    if kind == "lit": return re.escape(node[1]).replace("/", "\\/")
    if kind == "class": return "[\\s\\S]" if node[1] == "[^]" else node[1].replace("/", "\\/")
    if kind == "ref": return "(" + regex_of(rules[node[1]][0], rules) + ")"
    if kind == "seq": return "".join(regex_of(p, rules) for p in node[1])
    if kind == "alt": return "(" + "|".join(regex_of(p, rules) for p in node[1]) + ")"
    return "(" + regex_of(node[1], rules) + ")" + kind

def js_of(node):
    kind = node[0]
    if kind == "lit": return json.dumps(node[1])
    if kind == "class": return "/" + ("[\\s\\S]" if node[1] == "[^]" else node[1].replace("/", "\\/")) + "/"
    if kind == "ref": return None if node[1] in SKIP else f"$.{js_name(node[1])}"
    if kind == "seq":
        parts = [p for p in (js_of(x) for x in node[1]) if p]
        if not parts: return None
        return parts[0] if len(parts) == 1 else "seq(" + ", ".join(parts) + ")"
    if kind == "alt":
        parts = [js_of(x) for x in node[1]]
        if any(p is None for p in parts):
            rest = [p for p in parts if p]
            if not rest: return None
            inner = rest[0] if len(rest) == 1 else "choice(" + ", ".join(rest) + ")"
            return f"optional({inner})"
        return "choice(" + ", ".join(parts) + ")"
    inner = js_of(node[1])
    if inner is None: return None
    return {"*": "repeat", "+": "repeat1", "?": "optional"}[kind] + f"({inner})"

def tree_sitter(items):
    rules = {p[0]: (parse(p[1]), p[2]) for k, p in items if k == "rule"}
    out = ["// Soma grammar for tree-sitter — generated by tools/gen_grammar.py from spec/soma.grammar; do not edit.",
           "// A mechanical translation: precedence is in the layering of the expression rules, and the",
           "// places where the grammar is ambiguous without a lexer's line breaks are listed as conflicts.",
           "module.exports = grammar({", "  name: 'soma',", "",
           "  extras: $ => [/\\s/, $.comment],", "  word: $ => $.name,", "",
           "  conflicts: $ => [", "    [$.stmt, $.primary], [$.assign, $.primary], [$.record, $.primary], [$.lambda, $.primary],",
           "    [$.postfix], [$.return], [$.if], [$.try], [$.arm], [$.pattern, $.loose], [$.require],", "  ],", "",
           "  rules: {"]
    for kind, payload in items:
        if kind != "rule": continue
        name, _, lexical = payload
        if name in SKIP: continue
        node = rules[name][0]
        if lexical:
            body = "token(/" + regex_of(node, rules) + "/)"
        else:
            body = js_of(node) or "blank()"
        out.append(f"    {js_name(name)}: $ => {body},")
    out += ["  }", "});", ""]
    return "\n".join(out)

# ── write / check ──────────────────────────────────────────────────────

def main():
    items = read_source()
    names = [p[0] for k, p in items if k == "rule"]
    refs = set()
    def walk(n):
        if n[0] == "ref": refs.add(n[1])
        elif n[0] in ("seq", "alt"): [walk(x) for x in n[1]]
        elif n[0] in "*+?": walk(n[1])
    for k, p in items:
        if k == "rule": walk(parse(p[1]))
    missing = sorted(refs - set(names))
    if missing: raise SystemExit("spec/soma.grammar: undefined rule(s): " + ", ".join(missing))
    if len(names) != len(set(names)): raise SystemExit("spec/soma.grammar: a rule is defined twice")
    outputs = {
        os.path.join(ROOT, "spec", "soma.gbnf"): gbnf(items),
        os.path.join(ROOT, "spec", "grammar.md"): markdown(items),
        os.path.join(ROOT, "editors", "tree-sitter-soma", "grammar.js"): tree_sitter(items),
    }
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == text: continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(text)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        raise SystemExit("out of date (run tools/gen_grammar.py): " + ", ".join(stale))
    if check: print(f"{len(outputs)} grammar artifacts are up to date ({len(names)} rules)")

if __name__ == "__main__":
    main()
